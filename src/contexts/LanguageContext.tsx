// Context
// ============================================================================

const LanguageContext = createContext<LanguageContextType | null>(null)

const STORAGE_KEY = 'rstu-locale'

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')
  const [isHydrated, setIsHydrated] = useState(false)

  // Load saved locale AFTER hydration
  useEffect(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem(STORAGE_KEY) as Locale
      if (saved && SUPPORTED_LOCALES.some(l => l.code === saved)) {
        setLocaleState(saved)
      }
      setIsHydrated(true)
    }
  }, [])

  // Update document.lang only AFTER state updates (second render)
  useEffect(() => {
    if (isHydrated) {
      document.documentElement.lang = locale
    }
  }, [locale, isHydrated])

  // Set locale and persist
  const setLocale = useCallback((newLocale: Locale) => {
    setLocaleState(newLocale)
    if (typeof window !== 'undefined') {
      localStorage.setItem(STORAGE_KEY, newLocale)
    }
  }, [])

  // Translation function with parameter interpolation
  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    const translation = translations[locale][key] || translations['en'][key] || key

    if (!params) return translation

    // Replace {param} placeholders with values
    return Object.entries(params).reduce(
      (result, [param, value]) => result.replace(`{${param}}`, String(value)),
      translation
    )
  }, [locale])

  const value = useMemo(() => ({
    locale,
    setLocale,
    t,
    isLoading: !isHydrated
  }), [locale, setLocale, t, isHydrated])

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

// ============================================================================
// Hook
// ============================================================================

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider')
  }
  return context
}
